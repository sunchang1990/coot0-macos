#!/usr/bin/env python3
"""gen_licenses.py BUNDLE OUT_DIR ENV [ENV ...]

Writes OUT_DIR/THIRD_PARTY_LICENSES.md (one row per bundled component: name, version, licence, files) and copies the
licence texts that each conda package ships (pkgs/<pkg>/info/licenses) into OUT_DIR/licenses/<name>/.
Libraries are attributed to conda packages through conda-meta/*.json file lists; a few components that are not conda
packages (our canvas build, data) are described in EXTRA below.  Corrections of wrong conda metadata are in FIX.
"""
import collections, glob, json, os, shutil, sys

# conda metadata that is wrong or incomplete; the comment says how it was checked
FIX = {
    # the clipper package also ships FFTW 2 (libfftw.2 / librfftw.2); its info/licenses holds Clipper's COPYING = LGPL 2.1
    # and fftw2/COPYING = GPL 2 (FFTW 2.1.5: "version 2 of the License, or (at your option) any later version")
    "clipper": "LGPL-2.1 (Clipper); FFTW 2: GPL-2.0-or-later",
}
SPLIT = {"libfftw.2.dylib": ("fftw", "2.1.5", "GPL-2.0-or-later"), "librfftw.2.dylib": ("fftw", "2.1.5", "GPL-2.0-or-later")}
EXTRA = [  # (component, version, licence, where in the bundle, source)
    ("libart_lgpl", "2.3.21", "LGPL-2.0-or-later", "lib/libart_lgpl_2.2.dylib", "https://download.gnome.org/sources/libart_lgpl/2.3/"),
    ("libgnomecanvas", "2.30.3", "LGPL-2.0-or-later", "lib/libgnomecanvas-2.0.dylib", "https://download.gnome.org/sources/libgnomecanvas/2.30/"),
    ("goocanvas", "1.0.0", "LGPL-2.0-only", "lib/libgoocanvas.3.dylib", "https://download.gnome.org/sources/goocanvas/1.0/"),
    ("Monomer library (CCP4 / MonomerLibrary)", "commit 0af022bf", "LGPL-3.0", "monomers/", "https://github.com/MonomerLibrary/monomers"),
    ("RCrane (Kevin Keating)", "as in Coot 0.9.8.96", "ECL-2.0", "share/coot/python/rcrane/", "part of the Coot 0.9.8.96 source"),
    ("Python standard library", "3.11", "PSF-2.0", "lib/python3.11/", "https://www.python.org/downloads/source/"),
    ("Guile Scheme modules", "3.0.10", "LGPL-3.0-or-later", "share/guile/, lib/guile/", "https://ftp.gnu.org/gnu/guile/"),
]

def main():
    bundle, out = sys.argv[1], sys.argv[2]
    envs = sys.argv[3:]
    own, pkgdir = {}, {}
    for env in envs:
        for f in glob.glob(os.path.join(env, "conda-meta", "*.json")):
            d = json.load(open(f))
            key = (d["name"], d["version"])
            pkgdir[key] = d.get("extracted_package_dir") or ""
            for p in d.get("files", []):
                own.setdefault(os.path.basename(p), (d["name"], d["version"], d.get("license", "?")))
    rows = collections.OrderedDict(); unknown = []
    for dirpath, _, files in os.walk(os.path.join(bundle, "lib")):
        for fn in files:
            if not (fn.endswith(".dylib") or fn.endswith(".so")):
                continue
            o = SPLIT.get(fn) or own.get(fn)
            if o:
                rows.setdefault(o, []).append(os.path.relpath(os.path.join(dirpath, fn), bundle))
            elif fn not in ("libart_lgpl_2.2.dylib", "libgnomecanvas-2.0.dylib", "libgoocanvas.3.dylib"):
                unknown.append(os.path.relpath(os.path.join(dirpath, fn), bundle))
    os.makedirs(os.path.join(out, "licenses"), exist_ok=True)
    L = ["# Third-party components in the coot0 package", "",
         "Generated by `m0/tools/gen_licenses.py` from the conda package records of the build environments (`env/*.explicit.txt`).",
         "The licence texts each package ships are in `licenses/<package>/`.  Where to get the source of each: `CORRESPONDING_SOURCE.md`.", "",
         "| Component | Version | Licence (SPDX) | Files in the package |", "|---|---|---|---|"]
    for (name, ver, lic), files in sorted(rows.items(), key=lambda kv: kv[0][0].lower()):
        lic = FIX.get(name, lic)
        shown = ", ".join(sorted(files)[:3]) + (" and %d more" % (len(files) - 3) if len(files) > 3 else "")
        L.append("| %s | %s | %s | %s |" % (name, ver, lic, shown))
        src = os.path.join(pkgdir.get((name, ver), ""), "info", "licenses")
        if os.path.isdir(src):
            dst = os.path.join(out, "licenses", name)
            shutil.rmtree(dst, ignore_errors=True); shutil.copytree(src, dst)
    # packages that ship no info/licenses: FFTW 2 (its text is in the clipper package), FreeType (FTL / GPL-2, files from the
    # FreeType 2.14.3 source), SQLite (public domain): texts kept in m0/tools/licence-texts/<name>/
    here = os.path.dirname(os.path.abspath(__file__))
    fftw_src = os.path.join(out, "licenses", "clipper", "fftw2")
    if os.path.isdir(fftw_src):
        dst = os.path.join(out, "licenses", "fftw"); shutil.rmtree(dst, ignore_errors=True); shutil.copytree(fftw_src, dst)
    for name in ("libfreetype6", "libsqlite"):
        src = os.path.join(here, "licence-texts", name)
        if os.path.isdir(src):
            dst = os.path.join(out, "licenses", name); shutil.rmtree(dst, ignore_errors=True); shutil.copytree(src, dst)
    L += ["", "## Not from conda packages", "", "| Component | Version | Licence (SPDX) | In the package | Source |", "|---|---|---|---|---|"]
    for c in EXTRA:
        L.append("| %s | %s | %s | %s | %s |" % c)
    L += ["", "## Credits required by a licence", "",
          "- FreeType (lib/libfreetype.6.dylib, used under the FreeType License, FTL): Portions of this software are copyright \u00a9 "
          "2026 The FreeType Project (www.freetype.org). All rights reserved."]
    if unknown:
        L += ["", "## Not attributed (check by hand)", ""] + ["- " + u for u in sorted(unknown)]
    open(os.path.join(out, "THIRD_PARTY_LICENSES.md"), "w").write("\n".join(L) + "\n")
    print("rows", len(rows), "extra", len(EXTRA), "unattributed", len(unknown), "licence folders", len(os.listdir(os.path.join(out, "licenses"))))
    for u in unknown[:20]:
        print("  unattributed:", u)

if __name__ == "__main__":
    main()
